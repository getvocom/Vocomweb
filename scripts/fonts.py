#!/usr/bin/env python3
"""Self-host the exact webfont files the live Framer site loads.

Reads capture/fontfaces.css (every @font-face rule seen on the live site), keeps the
families/weights the design uses, downloads each woff2 to public/fonts/ and writes
src/styles/fonts.css with identical unicode-range splits.
Usage: python3 -I scripts/fonts.py <repo_root>
"""
import hashlib, re, sys, urllib.request
from pathlib import Path

ROOT = Path(sys.argv[1])
KEEP = {
    ("Inter", "normal"): {"400", "500", "600", "700", "800"},
    ("Inter Display", "normal"): {"400", "500", "600", "700", "800"},
    ("Inter Variable", "normal"): {"400"},
    ("Manrope", "normal"): {"500"},
    ("Lexend", "normal"): {"400", "500"},
    ("DM Sans", "normal"): {"500"},
}
out_dir = ROOT / "public/fonts"
out_dir.mkdir(parents=True, exist_ok=True)
rules, seen = [], set()
for rule in re.findall(r"@font-face\s*\{[^}]*\}", (ROOT / "capture/fontfaces.css").read_text()):
    fam = re.search(r"font-family:\s*['\"]?([^'\";]+)", rule).group(1).strip()
    style = (re.search(r"font-style:\s*(\w+)", rule) or [None, "normal"])[1]
    weight = (re.search(r"font-weight:\s*(\d+)", rule) or [None, "400"])[1]
    if weight not in KEEP.get((fam, style), set()):
        continue
    url = re.search(r"url\(([^)]+)\)", rule).group(1).strip("'\"")
    rng = re.search(r"unicode-range:\s*([^;}]+)", rule)
    key = (fam, weight, rng.group(1).strip() if rng else "")
    if key in seen:
        continue
    seen.add(key)
    name = f"{fam.lower().replace(' ', '-')}-{weight}-{hashlib.sha1(url.encode()).hexdigest()[:8]}.woff2"
    dest = out_dir / name
    if not dest.exists():
        req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
        dest.write_bytes(urllib.request.urlopen(req, timeout=60).read())
    variation = "font-weight:100 900;" if fam == "Inter Variable" else f"font-weight:{weight};"
    rules.append(
        f"@font-face{{font-family:\"{fam}\";font-style:normal;{variation}font-display:swap;"
        f"src:url(/fonts/{name}) format(\"woff2\");" + (f"unicode-range:{key[2]};" if key[2] else "") + "}"
    )
(ROOT / "src/styles").mkdir(parents=True, exist_ok=True)
(ROOT / "src/styles/fonts.css").write_text("/* Generated by scripts/fonts.py from the live site's @font-face rules. */\n" + "\n".join(rules) + "\n")
print(len(rules), "font-face rules,", len(list(out_dir.glob("*.woff2"))), "files")
