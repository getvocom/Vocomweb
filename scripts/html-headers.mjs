// Post-build: adds "Content-Type: text/html; charset=utf-8" for every HTML page to
// dist/_headers, so the charset is in the HTTP header as well as the <meta charset>.
// Cloudflare serves extensionless HTML as plain "text/html". Root pages get one rule each;
// /blog/* and /products/* hold only HTML pages, so one rule covers each folder.
import fs from "node:fs";

const rules = [];
for (const f of fs.readdirSync("dist").filter((f) => f.endsWith(".html")).sort()) {
  const name = f.replace(/\.html$/, "");
  rules.push(name === "index" ? "/" : "/" + name);
}
for (const dir of ["blog", "products"]) {
  if (fs.readdirSync(`dist/${dir}`).every((f) => f.endsWith(".html"))) rules.push(`/${dir}/*`);
  else throw new Error(`dist/${dir} has non-HTML files; a folder rule would mislabel them`);
}
const block = rules.map((r) => `${encodeURI(r)}\n  Content-Type: text/html; charset=utf-8`).join("\n");
fs.appendFileSync("dist/_headers", `\n# HTML charset (generated by scripts/html-headers.mjs)\n${block}\n`);
console.log(`_headers: charset rules for ${rules.length} paths`);
